#!/usr/bin/env bash
# =============================================================================
# AI SOFTWARE TECHNOLOGY — CLOUDFLARE ORIGIN IP LOCKDOWN SCRIPT
# Restricts inbound HTTP (80/tcp) and HTTPS (443/tcp) on the Ubuntu VPS UFW
# firewall strictly to official Cloudflare IPv4 and IPv6 edge ranges so
# attackers cannot bypass Cloudflare WAF/DDoS protection by hitting the origin
# VPS IP directly.
#
# Also updates /etc/nginx/snippets/ais-cloudflare-realip.conf with fresh ranges.
#
# Usage:
#   Lock down 80/443 to Cloudflare only:
#     sudo bash deploy/scripts/cloudflare-ufw-lockdown.sh
#   Rollback (re-allow direct public 80/443 if bypassing Cloudflare):
#     sudo bash deploy/scripts/cloudflare-ufw-lockdown.sh --rollback
# =============================================================================
set -euo pipefail

MODE="${1:-apply}"
REALIP_SNIPPET="/etc/nginx/snippets/ais-cloudflare-realip.conf"

if [ "$(id -u)" -ne 0 ]; then
  echo "ERROR: Run this script with sudo or as root."
  exit 1
fi

if [ "${MODE}" = "--rollback" ]; then
  echo "Re-allowing direct public HTTP (80/tcp) and HTTPS (443/tcp) in UFW..."
  ufw allow 80/tcp comment 'HTTP ACME & redirect'
  ufw allow 443/tcp comment 'HTTPS production web traffic'
  ufw reload
  echo "Rollback complete. Direct 80/443 access restored."
  exit 0
fi

echo "[1/4] Fetching official Cloudflare IPv4 and IPv6 CIDR lists..."
CF_IPV4="$(curl -fsS --max-time 10 https://www.cloudflare.com/ips-v4)"
CF_IPV6="$(curl -fsS --max-time 10 https://www.cloudflare.com/ips-v6)"

if [ -z "${CF_IPV4}" ] || [ -z "${CF_IPV6}" ]; then
  echo "ERROR: Failed to fetch Cloudflare IP lists. Aborting UFW changes."
  exit 1
fi

echo "[2/4] Updating ${REALIP_SNIPPET}..."
install -d -m 0755 /etc/nginx/snippets
{
  echo "# Auto-generated by cloudflare-ufw-lockdown.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  for ip in ${CF_IPV4}; do
    echo "set_real_ip_from ${ip};"
  done
  for ip6 in ${CF_IPV6}; do
    echo "set_real_ip_from ${ip6};"
  done
  echo "real_ip_header CF-Connecting-IP;"
  echo "real_ip_recursive on;"
} > "${REALIP_SNIPPET}"

if nginx -t >/dev/null 2>&1; then
  systemctl reload nginx || true
fi

echo "[3/4] Adding UFW allow rules for Cloudflare IPv4 & IPv6 ranges on ports 80 & 443..."
for ip in ${CF_IPV4}; do
  ufw allow proto tcp from "${ip}" to any port 80,443 comment 'Cloudflare IPv4 Edge'
done

for ip6 in ${CF_IPV6}; do
  ufw allow proto tcp from "${ip6}" to any port 80,443 comment 'Cloudflare IPv6 Edge'
done

echo "[4/4] Removing generic public 80/tcp and 443/tcp allow rules (preserving SSH)..."
ufw delete allow 80/tcp || true
ufw delete allow 443/tcp || true
ufw reload

echo "============================================================================="
echo "Cloudflare origin protection active: Ports 80 & 443 now accept traffic ONLY"
echo "from verified Cloudflare IPv4/IPv6 edge ranges. SSH access remains untouched."
echo "To revert if needed: sudo bash deploy/scripts/cloudflare-ufw-lockdown.sh --rollback"
echo "============================================================================="
